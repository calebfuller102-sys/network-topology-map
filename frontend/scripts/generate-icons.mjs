import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as mdi from "@mdi/js";
import * as simpleIcons from "simple-icons";

const require = createRequire(import.meta.url);
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendDirectory = dirname(scriptDirectory);
const repositoryDirectory = dirname(frontendDirectory);
const iconDirectory = join(frontendDirectory, "public", "icons");
const fontDirectory = join(frontendDirectory, "public", "fonts");
const generatedManifestPath = join(frontendDirectory, "src", "generated", "icon-manifest.ts");
const backendManifestPath = join(repositoryDirectory, "backend", "app", "icon_manifest.py");
const checkOnly = process.argv.includes("--check");

// This intentionally small list is the complete runtime allowlist. It keeps
