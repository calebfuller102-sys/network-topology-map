function valueFor(definition) {
  const library = definition.source === "mdi" ? mdi : simpleIcons;
  const value = library[definition.exportName];
  if (definition.source === "mdi" && typeof value === "string") {
    return value;
  }
  if (definition.source === "si" && value && typeof value.path === "string") {
    return value.path;
  }
  throw new Error(`Missing ${definition.source} export ${definition.exportName} for ${definition.id}`);
}

function svgFor(path) {
  // Paths come only from the pinned packages above; user input never reaches
  // this generator or the runtime renderer.
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="#79cde3"><path d="${path}"/></svg>\n`;
}

function frontendManifest(definitions) {
  const rows = definitions
    .map(
      ({ id, label, glyph }) =>
        `  { id: ${JSON.stringify(id)}, label: ${JSON.stringify(label)}, glyph: ${JSON.stringify(glyph)}, assetFile: ${JSON.stringify(`${id}.svg`)} },`,
    )
    .join("\n");
  return `// Generated by scripts/generate-icons.mjs. Do not edit manually.\n\nexport interface GeneratedIcon {\n  id: string;\n  label: string;\n  glyph: string;\n  assetFile: string;\n}\n\nexport const GENERATED_ICON_MANIFEST: readonly GeneratedIcon[] = [\n${rows}\n];\n`;
}

function backendManifest(definitions) {
  const ids = definitions.map(({ id }) => `        ${JSON.stringify(id)},`).join("\n");
  return `\"\"\"Generated local icon allowlist. Do not edit manually.\"\"\"\n\nICON_IDS = frozenset(\n    {\n${ids}\n    }\n)\n`;
}

async function sourceFile(packageName, relativePath) {
  const packageJson = require.resolve(`${packageName}/package.json`);
  return join(dirname(packageJson), relativePath);
}

async function writeOrCheck(path, contents) {
  if (checkOnly) {
    let existing;
    try {
      existing = await readFile(path);
    } catch {
      throw new Error(`Missing generated asset: ${path}`);
    }
    if (!existing.equals(Buffer.isBuffer(contents) ? contents : Buffer.from(contents))) {
      throw new Error(`Generated asset is stale: ${path}`);
    }
    return;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents);
}

async function main() {
  for (const definition of iconDefinitions) {
    await writeOrCheck(join(iconDirectory, `${definition.id}.svg`), svgFor(valueFor(definition)));
  }

  for (const font of fontDefinitions) {
    const fontContents = await readFile(await sourceFile(font.packageName, font.sourceFile));
    const licenseContents = await readFile(await sourceFile(font.packageName, font.licenseFile));
    await writeOrCheck(join(fontDirectory, font.outputFile), fontContents);
    await writeOrCheck(join(fontDirectory, font.outputLicenseFile), licenseContents);
  }

  await writeOrCheck(generatedManifestPath, frontendManifest(iconDefinitions));
  await writeOrCheck(backendManifestPath, backendManifest(iconDefinitions));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  console.error("Run `pnpm generate:icons` after installing the pinned frontend dependencies.");
  process.exitCode = 1;
});
